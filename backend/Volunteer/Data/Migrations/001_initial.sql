BEGIN;

CREATE TABLE IF NOT EXISTS t_schemamigration (
    migration_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL UNIQUE,
    applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS t_users (
    user_id uuid PRIMARY KEY,
    email varchar(256) NOT NULL UNIQUE,
    password_hash text NOT NULL,
    full_name varchar(200) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS t_privilege (
    privilege_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(64) NOT NULL UNIQUE,
    name varchar(120) NOT NULL
);

CREATE TABLE IF NOT EXISTS t_userprivilege (
    user_id uuid NOT NULL REFERENCES t_users (user_id) ON DELETE CASCADE,
    privilege_id smallint NOT NULL REFERENCES t_privilege (privilege_id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, privilege_id)
);

CREATE TABLE IF NOT EXISTS t_client (
    client_id uuid PRIMARY KEY,
    email varchar(256) NOT NULL UNIQUE,
    password_hash text NOT NULL,
    full_name varchar(200) NOT NULL,
    phone varchar(40),
    client_type varchar(32) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    email_verified_at timestamptz,
    closure_requested_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS t_volunteerprofile (
    client_id uuid PRIMARY KEY REFERENCES t_client (client_id) ON DELETE CASCADE,
    photo_path text,
    age integer,
    workplace_title varchar(200),
    country varchar(120),
    city varchar(120),
    availability varchar(200)
);

CREATE TABLE IF NOT EXISTS t_organisation (
    organisation_id uuid PRIMARY KEY,
    name varchar(200) NOT NULL,
    email varchar(256) NOT NULL,
    country varchar(120),
    contact_name varchar(200),
    contact_phone varchar(40),
    registration_no varchar(80),
    certificate_path text,
    logo_path text,
    mission text,
    vision text,
    description text,
    address text,
    city varchar(120),
    annual_work_plan text,
    budget_note text,
    special_requirements text,
    status varchar(32) NOT NULL DEFAULT 'pending',
    created_by_client_id uuid NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS t_organisationmember (
    organisation_id uuid NOT NULL REFERENCES t_organisation (organisation_id) ON DELETE CASCADE,
    client_id uuid NOT NULL REFERENCES t_client (client_id) ON DELETE CASCADE,
    member_role varchar(32) NOT NULL,
    PRIMARY KEY (organisation_id, client_id)
);

CREATE TABLE IF NOT EXISTS t_skill (
    skill_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL UNIQUE,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS t_hobby (
    hobby_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL UNIQUE,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS t_focusarea (
    focus_area_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL UNIQUE,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS t_category (
    category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL UNIQUE,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS t_volunteerskill (
    client_id uuid NOT NULL REFERENCES t_volunteerprofile (client_id) ON DELETE CASCADE,
    skill_id integer NOT NULL REFERENCES t_skill (skill_id),
    PRIMARY KEY (client_id, skill_id)
);

CREATE TABLE IF NOT EXISTS t_volunteerhobby (
    client_id uuid NOT NULL REFERENCES t_volunteerprofile (client_id) ON DELETE CASCADE,
    hobby_id integer NOT NULL REFERENCES t_hobby (hobby_id),
    PRIMARY KEY (client_id, hobby_id)
);

CREATE TABLE IF NOT EXISTS t_volunteerfocus (
    client_id uuid NOT NULL REFERENCES t_volunteerprofile (client_id) ON DELETE CASCADE,
    focus_area_id integer NOT NULL REFERENCES t_focusarea (focus_area_id),
    PRIMARY KEY (client_id, focus_area_id)
);

CREATE TABLE IF NOT EXISTS t_organisationfocus (
    organisation_id uuid NOT NULL REFERENCES t_organisation (organisation_id) ON DELETE CASCADE,
    focus_area_id integer NOT NULL REFERENCES t_focusarea (focus_area_id),
    PRIMARY KEY (organisation_id, focus_area_id)
);

CREATE TABLE IF NOT EXISTS t_organisationpaymentlink (
    link_id uuid PRIMARY KEY,
    organisation_id uuid NOT NULL REFERENCES t_organisation (organisation_id) ON DELETE CASCADE,
    provider varchar(40) NOT NULL,
    label varchar(120),
    url_or_account text NOT NULL
);

CREATE TABLE IF NOT EXISTS t_opportunity (
    opportunity_id uuid PRIMARY KEY,
    organisation_id uuid NOT NULL REFERENCES t_organisation (organisation_id) ON DELETE CASCADE,
    title varchar(200) NOT NULL,
    description text NOT NULL,
    video_url text,
    category_id integer REFERENCES t_category (category_id),
    location varchar(200),
    is_remote boolean NOT NULL DEFAULT false,
    eligibility text,
    starts_on date,
    ends_on date,
    time_commitment varchar(120),
    volunteer_count integer,
    deadline date,
    is_paid boolean NOT NULL DEFAULT false,
    special_requirements text,
    coordinator_name varchar(200),
    coordinator_phone varchar(40),
    status varchar(32) NOT NULL DEFAULT 'draft',
    is_flagged boolean NOT NULL DEFAULT false,
    flag_reason text,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS t_opportunityskill (
    opportunity_id uuid NOT NULL REFERENCES t_opportunity (opportunity_id) ON DELETE CASCADE,
    skill_id integer NOT NULL REFERENCES t_skill (skill_id),
    PRIMARY KEY (opportunity_id, skill_id)
);

CREATE TABLE IF NOT EXISTS t_opportunityquestion (
    question_id uuid PRIMARY KEY,
    opportunity_id uuid NOT NULL REFERENCES t_opportunity (opportunity_id) ON DELETE CASCADE,
    prompt text NOT NULL,
    is_required boolean NOT NULL DEFAULT false,
    sort_order integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS t_application (
    application_id uuid PRIMARY KEY,
    opportunity_id uuid NOT NULL REFERENCES t_opportunity (opportunity_id) ON DELETE CASCADE,
    client_id uuid NOT NULL REFERENCES t_client (client_id) ON DELETE CASCADE,
    motivation text,
    status varchar(32) NOT NULL DEFAULT 'submitted',
    submitted_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    UNIQUE (opportunity_id, client_id)
);

CREATE TABLE IF NOT EXISTS t_applicationanswer (
    answer_id uuid PRIMARY KEY,
    application_id uuid NOT NULL REFERENCES t_application (application_id) ON DELETE CASCADE,
    question_id uuid NOT NULL REFERENCES t_opportunityquestion (question_id),
    answer_text text NOT NULL
);

CREATE TABLE IF NOT EXISTS t_storedfile (
    file_id uuid PRIMARY KEY,
    file_name varchar(260) NOT NULL,
    content_type varchar(120) NOT NULL,
    storage_path text NOT NULL,
    is_public boolean NOT NULL DEFAULT false,
    public_path text,
    owner_client_id uuid,
    owner_user_id uuid,
    created_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS t_applicationdocument (
    document_id uuid PRIMARY KEY,
    application_id uuid NOT NULL REFERENCES t_application (application_id) ON DELETE CASCADE,
    file_id uuid NOT NULL REFERENCES t_storedfile (file_id)
);

CREATE TABLE IF NOT EXISTS t_applicationreview (
    application_id uuid PRIMARY KEY REFERENCES t_application (application_id) ON DELETE CASCADE,
    internal_note text,
    volunteer_note text,
    rating integer,
    attended boolean,
    reviewed_by_client_id uuid,
    updated_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS t_notification (
    notification_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient varchar(256) NOT NULL,
    subject varchar(200) NOT NULL,
    body text NOT NULL,
    status varchar(32) NOT NULL DEFAULT 'logged',
    error text,
    created_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS t_auditlog (
    audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid,
    client_id uuid,
    action varchar(80) NOT NULL,
    entity_name varchar(80) NOT NULL,
    entity_id varchar(80) NOT NULL,
    detail text,
    created_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS t_report (
    report_id uuid PRIMARY KEY,
    opportunity_id uuid,
    organisation_id uuid,
    reported_by_client_id uuid NOT NULL,
    reason text NOT NULL,
    status varchar(32) NOT NULL DEFAULT 'open',
    created_at timestamptz NOT NULL,
    reviewed_by_user_id uuid
);

CREATE TABLE IF NOT EXISTS t_emailtoken (
    token_id uuid PRIMARY KEY,
    client_id uuid NOT NULL REFERENCES t_client (client_id) ON DELETE CASCADE,
    purpose varchar(32) NOT NULL,
    token_hash text NOT NULL,
    expires_at timestamptz NOT NULL,
    used_at timestamptz
);

CREATE TABLE IF NOT EXISTS t_refreshtoken (
    token_id uuid PRIMARY KEY,
    account_type varchar(16) NOT NULL,
    account_id uuid NOT NULL,
    token_hash text NOT NULL,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL,
    revoked_at timestamptz
);

