CREATE OR REPLACE PROCEDURE p_setnotification(Code VARCHAR, IsEnabled BOOLEAN)
LANGUAGE plpgsql
AS $$
DECLARE
    v_code varchar(64);
BEGIN
    v_code := NULLIF(lower(btrim(Code)), '');
    IF v_code IS NULL OR IsEnabled IS NULL THEN
        RAISE EXCEPTION 'Choose a notification.'
            USING ERRCODE = '22023';
    END IF;

    UPDATE t_notificationsetting AS note
    SET is_enabled = IsEnabled
    WHERE note.code = v_code;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'That notification is not on file.'
            USING ERRCODE = 'P0002';
    END IF;
END;
$$;

