CREATE OR REPLACE FUNCTION p_liststaff()
RETURNS TABLE (
    user_id uuid,
    email varchar,
    full_name varchar,
    is_active boolean,
    roles text
)
LANGUAGE sql
AS $$
    SELECT staff.user_id, staff.email, staff.full_name, staff.is_active,
        COALESCE(string_agg(privilege.name, ', ' ORDER BY privilege.name), '')
    FROM t_users AS staff
    LEFT JOIN t_userprivilege AS link ON link.user_id = staff.user_id
    LEFT JOIN t_privilege AS privilege ON privilege.privilege_id = link.privilege_id
    GROUP BY staff.user_id, staff.email, staff.full_name, staff.is_active
    ORDER BY staff.full_name;
$$;

CREATE OR REPLACE PROCEDURE p_addstaff
(
    Email VARCHAR,
    PasswordHash TEXT,
    FullName VARCHAR,
    PrivilegeCode VARCHAR,
    INOUT UserID UUID
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_email varchar(256);
    v_name varchar(200);
    v_code varchar(64);
    v_privilege smallint;
BEGIN
    v_email := NULLIF(lower(btrim(Email)), '');
    v_name := NULLIF(btrim(FullName), '');
    v_code := NULLIF(lower(btrim(PrivilegeCode)), '');
    IF v_email IS NULL OR v_name IS NULL OR PasswordHash IS NULL OR btrim(PasswordHash) = '' OR v_code IS NULL THEN
        RAISE EXCEPTION 'Enter a name, email, password, and role.'
            USING ERRCODE = '22023';
    END IF;

    SELECT privilege.privilege_id INTO v_privilege
    FROM t_privilege AS privilege
    WHERE privilege.code = v_code;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Choose a role that exists.'
            USING ERRCODE = '22023';
    END IF;

    UserID := gen_random_uuid();
    INSERT INTO t_users (user_id, email, password_hash, full_name, is_active, created_at, updated_at)
    VALUES (UserID, v_email, PasswordHash, v_name, true, clock_timestamp(), clock_timestamp());

    INSERT INTO t_userprivilege (user_id, privilege_id)
    VALUES (UserID, v_privilege);
END;
$$;

CREATE OR REPLACE PROCEDURE p_setstaffactive(UserID UUID, IsActive BOOLEAN)
LANGUAGE plpgsql
AS $$
BEGIN
    IF UserID IS NULL OR IsActive IS NULL THEN
        RAISE EXCEPTION 'Choose an admin account.'
            USING ERRCODE = '22023';
    END IF;

    IF NOT IsActive AND NOT EXISTS (
        SELECT 1
        FROM t_users AS staff
        JOIN t_userprivilege AS link ON link.user_id = staff.user_id
        JOIN t_privilege AS privilege ON privilege.privilege_id = link.privilege_id
        WHERE staff.is_active
          AND privilege.code = 'admin'
          AND staff.user_id <> UserID
    ) THEN
        RAISE EXCEPTION 'Keep at least one active administrator.'
            USING ERRCODE = '22023';
    END IF;

    UPDATE t_users AS staff
    SET is_active = IsActive,
        updated_at = clock_timestamp()
    WHERE staff.user_id = UserID;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'No admin account uses that id.'
            USING ERRCODE = 'P0002';
    END IF;
END;
$$;

