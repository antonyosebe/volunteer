CREATE OR REPLACE PROCEDURE p_savesettings(SiteName VARCHAR, SupportEmail VARCHAR, Tagline VARCHAR)
LANGUAGE plpgsql
AS $$
DECLARE
    v_name text;
    v_email text;
    v_tagline text;
BEGIN
    v_name := NULLIF(btrim(SiteName), '');
    v_email := NULLIF(lower(btrim(SupportEmail)), '');
    v_tagline := NULLIF(btrim(Tagline), '');
    IF v_name IS NULL OR v_email IS NULL OR v_tagline IS NULL THEN
        RAISE EXCEPTION 'Enter the site name, support email, and tagline.'
            USING ERRCODE = '22023';
    END IF;

    UPDATE t_applicationsetting AS setting SET setting_value = v_name WHERE setting.setting_key = 'site_name';
    UPDATE t_applicationsetting AS setting SET setting_value = v_email WHERE setting.setting_key = 'support_email';
    UPDATE t_applicationsetting AS setting SET setting_value = v_tagline WHERE setting.setting_key = 'tagline';
END;
$$;

