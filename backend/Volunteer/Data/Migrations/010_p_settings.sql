CREATE OR REPLACE PROCEDURE p_addprivilege(Code VARCHAR, Name VARCHAR)
LANGUAGE plpgsql
AS $$
DECLARE
    v_code varchar(64);
    v_name varchar(120);
BEGIN
    v_code := NULLIF(lower(btrim(Code)), '');
    v_name := NULLIF(btrim(Name), '');
    IF v_code IS NULL OR v_name IS NULL OR v_code !~ '^[a-z][a-z0-9_]{1,63}$' THEN
        RAISE EXCEPTION 'Use a short code such as reviewer, and a name.'
            USING ERRCODE = '22023';
    END IF;

    INSERT INTO t_privilege (code, name)
    VALUES (v_code, v_name);
END;
$$;

